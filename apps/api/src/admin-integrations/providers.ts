const BY_KEY = new Map(PROVIDERS.map((p) => [p.key, p]));
const CUSTOM = BY_KEY.get('custom') as ProviderDefinition;

/** A provider's definition; `custom_…` and unknown keys use the generic one. */
export const providerFor = (key: string): ProviderDefinition => BY_KEY.get(key) ?? CUSTOM;

/** A known template key (not `custom`, which names nothing on its own). */
export const isTemplateKey = (key: string): boolean => key !== 'custom' && BY_KEY.has(key);

/** The wizard's list, without the internal `critical` flag. */
export const providerTemplates = (): AdminProviderTemplate[] =>
  PROVIDERS.map(({ critical: _critical, ...template }) => template);
