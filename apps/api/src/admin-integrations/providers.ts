import type {
  AdminConnectionField,
  AdminProviderTemplate,
  IntegrationEnvironment,
} from '@firmivra/types';

// The services Firmivra knows how to connect as platform integrations (spec 14, B8: provider
// definitions stay in code). The fields, scopes and features are the wizard's; `custom` covers any
// other provider. Only the Stripe webhook route exists today (/api/v1/webhooks/stripe), so only
// Stripe names a webhook path. `critical`: Firmivra runs on it, so removing the live connection
// needs the name typed.

export interface ProviderDefinition extends AdminProviderTemplate {
  critical: boolean;
}

const secret = (
  key: string,
  label: string,
  placeholder: string,
  prefix: Record<IntegrationEnvironment, string> | null = null,
  hint: string | null = null,
): AdminConnectionField => ({
  key,
  label,
  secret: true,
  required: true,
  kind: 'text',
  placeholder,
  hint,
  prefix,
});
const plain = (
  key: string,
  label: string,
  placeholder: string,
  options: {
    required?: boolean;
    kind?: 'text' | 'url';
    prefix?: Record<IntegrationEnvironment, string>;
  } = {},
): AdminConnectionField => ({
  key,
  label,
  secret: false,
  required: options.required ?? true,
  kind: options.kind ?? 'text',
  placeholder,
  hint: null,
  prefix: options.prefix ?? null,
});
const both = (prefix: string) => ({ LIVE: prefix, TEST: prefix });

